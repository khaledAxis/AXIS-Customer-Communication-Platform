/**
 * The QA email allowlist (ADR-0027).
 *
 * A SEPARATE safety mechanism from the SAFE TEST hard-lock, deliberately. SAFE TEST
 * still reaches exactly one address and its policy is untouched; this path reaches
 * exactly FOUR, and neither can reach the other's addresses because neither knows
 * about the other's constants.
 *
 * The audience is UNREPRESENTABLE rather than merely validated, exactly as in
 * ADR-0013/0025: `QaMessage` has no `from`, `cc`, `bcc` or `replyTo` field, and `to`
 * is a single string chosen from a closed set. There is no shape in which a caller
 * could express a fifth recipient.
 *
 * The allowlist is a hard-coded constant. It is NEVER derived from — and this file
 * imports nothing from — Monday, the CRM projection, `CommunicationAddress`,
 * `Segment`, `CampaignRecipient`, or any audience. A test asserts that against the
 * source, because "we would never" is not a control.
 *
 * Pure: no I/O, no framework imports.
 */

/**
 * The ONLY four addresses a QA email may reach.
 *
 * Exact string equality after lower-casing and trimming. No alias expansion, no
 * plus-address variants, no display-name form, no domain wildcard.
 */
export const QA_ALLOWED_RECIPIENTS = [
  "khaled-s@axis-gps.com",
  "moaawya@axis-gps.com",
  "info@axis-gps.com",
  "saja@axis-gps.com",
] as const;

export type QaRecipient = (typeof QA_ALLOWED_RECIPIENTS)[number];

/** Frozen set for O(1) membership. Never mutated, never extended at runtime. */
const ALLOWED = new Set<string>(QA_ALLOWED_RECIPIENTS);

/**
 * Every QA subject begins with this, so a recipient can tell from the inbox list
 * alone that the message is an internal platform test and not a customer newsletter.
 */
export const QA_SUBJECT_PREFIX = "[AXIS Newsletter Platform TEST]" as const;

/** Applied exactly once — re-rendering must never produce a doubled prefix. */
export function applyQaSubjectPrefix(subject: string): string {
  const trimmed = subject.trim();
  if (trimmed.startsWith(QA_SUBJECT_PREFIX)) return trimmed;
  return `${QA_SUBJECT_PREFIX} ${trimmed}`;
}

export function hasQaSubjectPrefix(subject: string): boolean {
  return subject.trimStart().startsWith(QA_SUBJECT_PREFIX);
}

