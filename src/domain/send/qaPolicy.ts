/**
 * Caps, enforced server-side.
 *
 * These are a safety limit, not a target. Exceeding them is refused rather than
 * warned about — a runaway loop that mails a colleague forty times is exactly what a
 * hard stop is for.
 */
export const QA_RECOMMENDED_TOTAL = 32;
export const QA_HARD_TOTAL = 40;
export const QA_HARD_PER_RECIPIENT = 10;

export interface QaCapState {
  totalSent: number;
  sentToRecipient: number;
}

export function isWithinQaCaps(state: QaCapState): boolean {
  return (
    state.totalSent < QA_HARD_TOTAL &&
    state.sentToRecipient < QA_HARD_PER_RECIPIENT
  );
}
