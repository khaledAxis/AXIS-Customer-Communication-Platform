export type QaEnvelopeRejection =
  | "NOT_ALLOWED_RECIPIENT"
  | "MULTIPLE_RECIPIENTS"
  | "COPY_RECIPIENTS_FORBIDDEN"
  | "HEADER_INJECTION"
  | "NOT_A_STRING"
  | "DISPLAY_NAME_FORM"
  | "PLUS_ALIAS"
  | "MISSING_SUBJECT_PREFIX";

export const QA_ENVELOPE_MESSAGE: Record<QaEnvelopeRejection, string> = {
  NOT_ALLOWED_RECIPIENT:
    "That address is not on the QA list. QA email can only be sent to the four approved AXIS addresses.",
  MULTIPLE_RECIPIENTS: "A QA email has exactly one recipient.",
  COPY_RECIPIENTS_FORBIDDEN: "A QA email cannot carry CC or BCC recipients.",
  HEADER_INJECTION: "That address contains characters that are not allowed.",
  NOT_A_STRING: "That is not an email address.",
  DISPLAY_NAME_FORM:
    "Enter the address on its own — a display name such as \"Name <address>\" is not accepted.",
  PLUS_ALIAS:
    "Plus-address variants are not on the QA list. Use the exact approved address.",
  MISSING_SUBJECT_PREFIX: `A QA email subject must begin with ${QA_SUBJECT_PREFIX}.`,
};

export class UnsafeQaEnvelopeError extends Error {
  readonly reason: QaEnvelopeRejection;

  constructor(reason: QaEnvelopeRejection) {
    super(QA_ENVELOPE_MESSAGE[reason]);
    this.name = "UnsafeQaEnvelopeError";
    this.reason = reason;
  }
}

export function isAllowedQaRecipient(address: unknown): address is QaRecipient {
  return typeof address === "string" && ALLOWED.has(address.trim().toLowerCase());
}

/**
 * Anything that could widen a QA message's audience.
 *
 * Accepts `unknown` deliberately: this is the last gate before the network, so it must
 * be able to refuse a shape the type system was told could not exist.
 */
export interface QaEnvelopeCandidate {
  to: unknown;
  cc?: unknown;
  bcc?: unknown;
  subject?: unknown;
}

/**
 * The gate. REFUSES rather than repairs.
 *
 * A caller-supplied `cc` is not quietly dropped, a display-name wrapper is not parsed
 * down to its address, and a plus-alias is not normalised to its base — every one of
 * those is a rejection, because a caller that supplied one has misunderstood something
 * and the safe response is to stop rather than to guess what they meant.
 *
 * Returns the address in canonical allowlist form, NOT the caller's string, so a
 * homoglyph or a stray character cannot survive the gate.
 */
export function assertSafeQaEnvelope(candidate: QaEnvelopeCandidate): QaRecipient {
  if (candidate.cc !== undefined || candidate.bcc !== undefined) {
    throw new UnsafeQaEnvelopeError("COPY_RECIPIENTS_FORBIDDEN");
  }
  if (Array.isArray(candidate.to)) {
    throw new UnsafeQaEnvelopeError("MULTIPLE_RECIPIENTS");
  }
  if (typeof candidate.to !== "string") {
    // null, undefined, numbers, objects — anything that is not a plain string.
    throw new UnsafeQaEnvelopeError("NOT_A_STRING");
  }

  // Checked on the RAW value, before trimming: trimming a trailing newline first
  // would hide the very injection this is looking for.
  if (hasHeaderInjection(candidate.to)) {
    throw new UnsafeQaEnvelopeError("HEADER_INJECTION");
  }

  const raw = candidate.to.trim();
  if (raw === "") throw new UnsafeQaEnvelopeError("NOT_A_STRING");

  // A comma or semicolon is a second recipient smuggled into one string.
  if (raw.includes(",") || raw.includes(";")) {
    throw new UnsafeQaEnvelopeError("MULTIPLE_RECIPIENTS");
  }
  // `Name <addr>` — refused outright rather than unwrapped.
  if (raw.includes("<") || raw.includes(">")) {
    throw new UnsafeQaEnvelopeError("DISPLAY_NAME_FORM");
  }
  // Reported specifically, because `khaled-s+qa@axis-gps.com` delivers to a real
  // mailbox and would otherwise look like a harmless variation of an approved address.
  if (raw.includes("+")) {
    throw new UnsafeQaEnvelopeError("PLUS_ALIAS");
  }

  if (!isAllowedQaRecipient(raw)) {
    throw new UnsafeQaEnvelopeError("NOT_ALLOWED_RECIPIENT");
  }

  if (candidate.subject !== undefined) {
    if (typeof candidate.subject !== "string" || !hasQaSubjectPrefix(candidate.subject)) {
      throw new UnsafeQaEnvelopeError("MISSING_SUBJECT_PREFIX");
    }
    if (hasHeaderInjection(candidate.subject)) {
      throw new UnsafeQaEnvelopeError("HEADER_INJECTION");
    }
  }

  // The CONSTANT, never the caller's string.
  const canonical = QA_ALLOWED_RECIPIENTS.find(
    (allowed) => allowed === raw.toLowerCase(),
  );
  if (!canonical) throw new UnsafeQaEnvelopeError("NOT_ALLOWED_RECIPIENT");
  return canonical;
}

