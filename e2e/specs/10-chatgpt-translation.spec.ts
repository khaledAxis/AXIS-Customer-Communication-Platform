import { expect, test } from "@playwright/test";
import { loginAsAdmin, PageErrors } from "../support";

test("regular ChatGPT copy/paste creates a reviewed RTL draft without API access", async ({ page, context }, testInfo) => {
  const errors = new PageErrors(page);
  const creds = await loginAsAdmin(page);
  // A dedicated synthetic original keeps this test independent of other review fixtures.
  const title = "e2e External field mapping with NavVis CLX";
  await page.goto("/content/new");
  await page.locator('input[name="title"]').fill(title);
  await page.locator("label").filter({ has: page.locator('input[name="language"][value="UNKNOWN"]') }).click();
  await page.locator("label").filter({ has: page.locator('input[name="origin"][value="INGESTED"]') }).click();
  await page.locator('textarea[name="summary"]').fill("Capture point clouds at 40 m…");
  await page.locator('input[name="sourceName"]').fill("e2e Synthetic ChatGPT source");
  await page.locator('input[name="externalUrl"]').fill("https://example.com/field-mapping");
  await page.getByRole("button", { name: "Save article", exact: true }).click();
  await expect(page).toHaveURL(/\/content\/[^/]+\/edit\?saved=1/);
  const originalUrl = page.url();
  await expect(page.getByRole("button", { name: "Use ChatGPT · no API credits", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByText("Article text missing — only the title and excerpt are available", { exact: true })).toBeVisible();
  await expect(page.getByText("The excerpt ends with an ellipsis (…) and may be incomplete.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Prepare title and excerpt only", exact: true }).click();
  await page.getByText("View or select the prepared prompt", { exact: true }).click();
  const excerptPrompt = await page.getByRole("textbox", { name: "Translation prompt", exact: true }).inputValue();
  expect(excerptPrompt).toContain("No article body text is included");
  const excerptData = JSON.parse(excerptPrompt.split("ARTICLE_DATA:\n")[1]) as { sourceRef: string; segments: { id: string; text: string }[] };
  expect(excerptData.segments).toHaveLength(2);
  await page.getByText("View or select the prepared prompt", { exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByText("Article text missing — only the title and excerpt are available", { exact: true }).scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("missing-article-mobile.png") });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("link", { name: "Add full article text", exact: true }).click();
  await expect(page).toHaveURL(/#article-text$/);
  await expect(page.getByRole("region", { name: "Add or edit article text" })).toBeInViewport();
  await page.getByRole("textbox", { name: "Article text", exact: true }).fill("## Surveying\n\nThe **NavVis CLX** creates point clouds.\n\n- Accuracy: 5 mm\n\n[Read the source](https://example.com/field-mapping)\n\nFinal passage of the supplied article.");
  await page.getByRole("button", { name: "Save changes", exact: true }).click();
  await expect(page.getByText("Your changes have been saved.", { exact: true })).toBeVisible();
  await expect(page.getByText(/^Saved article text included ·/)).toBeVisible();
  // Saving changed source text must clear the earlier excerpt preparation without a reload.
  await expect(page.getByRole("button", { name: "Copy prompt", exact: true })).toHaveCount(0);
  await page.getByText("Text included in this translation", { exact: true }).click();
  await expect(page.locator("dd").filter({ hasText: "Final passage of the supplied article." })).toBeVisible();
  await page.getByText("Text included in this translation", { exact: true }).click();
  await page.getByRole("button", { name: "Prepare for ChatGPT", exact: true }).click();
  await page.getByText("View or select the prepared prompt", { exact: true }).click();
  const prompt = page.getByRole("textbox", { name: "Translation prompt", exact: true });
  await expect(prompt).toHaveValue(/ARTICLE_DATA:/);
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.getByRole("button", { name: "Copy prompt", exact: true }).click();
  await expect(page.getByText("Copied. Paste it into ChatGPT and send it.", { exact: true })).toBeVisible();
  // Windows clipboard text uses CRLF; textareas expose normalized LF.
  const copied = (await page.evaluate(() => navigator.clipboard.readText())).replace(/\r\n?/g, "\n");
  expect(copied).toBe(await prompt.inputValue());
  await page.getByText("View or select the prepared prompt", { exact: true }).click();
  await expect(page.getByRole("link", { name: "Open ChatGPT ↗", exact: true })).toHaveAttribute("href", "https://chatgpt.com/");
  // A constructed reply tests import behavior; no request is sent to ChatGPT or OpenAI.
  const source = JSON.parse(copied.split("ARTICLE_DATA:\n")[1]) as { sourceRef: string; segments: { id: string; text: string }[] };
  expect(source.sourceRef).not.toBe(excerptData.sourceRef);
  expect(source.segments.some(row => row.text === "Final passage of the supplied article.")).toBe(true);
  const reply = JSON.stringify({ ...source, segments: source.segments.map(row => ({ ...row, text: `תרגום בדיקה ${row.text}` })) });
  const responseBox = page.getByRole("textbox", { name: "3. Paste ChatGPT’s reply", exact: true });
  await responseBox.fill("Incomplete response");
  await page.getByRole("button", { name: "Save Hebrew draft", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "That reply could not be read" })).toBeVisible();
  await responseBox.fill(reply);
  await expect(page.getByRole("alert").filter({ hasText: "That reply could not be read" })).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.getByRole("button", { name: "Copy prompt", exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("chatgpt-manual-mobile.png") });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("button", { name: "Copy prompt", exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("chatgpt-manual-desktop.png") });
  await page.getByRole("button", { name: "Save Hebrew draft", exact: true }).click();
  await expect(page).toHaveURL(/translated=1/);
  const translatedUrl = page.url(); expect(translatedUrl).not.toBe(originalUrl);
  await expect(page.getByRole("heading", { name: "Hebrew translation — review before approval" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Approve", exact: true })).toBeVisible();
  await expect(page.getByRole("textbox", { name: "Article text", exact: true })).toHaveAttribute("dir", "rtl");
  await expect(page.getByRole("textbox", { name: "Article text", exact: true })).toHaveValue(/Final passage of the supplied article/);
  await page.reload();
  await expect(page.locator('input[name="title"]')).toHaveValue(/תרגום בדיקה/);
  const translatedTitle = await page.locator('input[name="title"]').inputValue();
  await page.goto(`/newsletters/${creds.fixtures.campaignId}`);
  await expect(page.getByText(translatedTitle, { exact: true })).toHaveCount(0);
  await page.goto(originalUrl);
  await expect(page.locator('input[name="title"]')).toHaveValue(title);
  await expect(page.getByRole("link", { name: "Review Hebrew version", exact: true })).toHaveAttribute("href", translatedUrl.replace("?translated=1", "").replace(/^https?:\/\/[^/]+/, ""));
  errors.assertClean("regular ChatGPT article import");
});
