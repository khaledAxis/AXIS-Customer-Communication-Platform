import { expect, test } from "@playwright/test";
import { loginAsAdmin, PageErrors } from "../support";

test("Hebrew drafts require review and retain RTL through editing and email preview", async ({ page }, testInfo) => {
  const errors = new PageErrors(page);
  const creds = await loginAsAdmin(page);
  await page.goto(`/content/inbox/${creds.fixtures.pendingArticleId}`);
  await page.getByRole("button", { name: "Automatic translation · API", exact: true }).click();
  await expect(page.getByRole("button", { name: "Translate title and excerpt only", exact: true })).toBeDisabled();
  await expect(page.getByText(/Hebrew translation needs an OpenAI API key/)).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("hebrew-translation-entry.png") });
  await page.getByRole("link", { name: "Review Hebrew version", exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/content/${creds.fixtures.translatedArticleId}/edit`));
  await expect(page.getByRole("heading", { name: "Hebrew translation — review before approval" })).toBeVisible();
  await expect(page.getByText("e2e Waiting article one", { exact: true })).toBeVisible();
  await expect(page.getByText(/original article has changed since/)).toBeVisible();
  await page.goto(`/content/inbox/${creds.fixtures.translatedArticleId}`);
  await expect(page.getByRole("heading", { name: "Prepared Hebrew draft", exact: true })).toBeVisible();
  await expect(page.getByText(/publisher’s own text/)).toHaveCount(0);
  await page.getByRole("link", { name: "Compare with the original and edit the Hebrew article", exact: true }).click();
  await expect(page.locator('input[name="language"][value="HE"]')).toBeChecked();
  const editor = page.getByRole("textbox", { name: "Article text", exact: true });
  await expect(editor).toHaveAttribute("dir", "rtl");
  const title = await page.locator('input[name="title"]').inputValue();
  await editor.fill((await editor.inputValue()) + "\n\nהטקסט נבדק ונערך על ידי צוות הבדיקה.");
  await page.getByRole("button", { name: "Save changes", exact: true }).click();
  await expect(page.getByText("Your changes have been saved.", { exact: true })).toBeVisible();
  await page.reload();
  await expect(editor).toHaveValue(/הטקסט נבדק/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("hebrew-review-mobile.png") });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: testInfo.outputPath("hebrew-review-desktop.png") });

  await page.goto(`/newsletters/${creds.fixtures.campaignId}`);
  await expect(page.getByText(title, { exact: true })).toHaveCount(0);
  await page.goto(`/content/${creds.fixtures.translatedArticleId}/edit`);
  await page.getByRole("button", { name: "Approve", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve", exact: true })).toHaveCount(0);
  await page.goto(`/newsletters/${creds.fixtures.campaignId}`);
  await page.locator("li").filter({ has: page.getByText(title, { exact: true }) }).getByRole("button", { name: "Add", exact: true }).click();
  await expect(page.locator("ol li").filter({ hasText: title })).toBeVisible();
  await page.getByRole("link", { name: "Preview email", exact: true }).click();
  const email = page.frameLocator("iframe").first();
  await expect(email.locator('strong span[dir="ltr"]').filter({ hasText: "NavVis CLX" })).toBeVisible();
  await expect(email.locator('span[dir="ltr"]').filter({ hasText: /^40 m$/ }).first()).toBeVisible();
  await expect(email.getByRole("link", { name: "לכתבה המקורית", exact: true })).toHaveAttribute("href", "https://fixtures.example.com/article-0");
  await expect(email.locator('table[dir="rtl"]').first()).toBeVisible();
  await page.getByRole("button", { name: "Phone", exact: true }).click();
  await expect(email.getByText("הטקסט נבדק ונערך על ידי צוות הבדיקה.", { exact: true })).toBeVisible();
  await email.getByRole("heading", { name: title, exact: true }).scrollIntoViewIfNeeded();
  await page.locator("iframe").first().screenshot({ path: testInfo.outputPath("hebrew-email-phone.png") });
  errors.assertClean("Hebrew translation review workflow");

  await page.goto(`/newsletters/${creds.fixtures.campaignId}`);
  await page.locator("ol li").filter({ hasText: title }).getByRole("button", { name: "Remove", exact: true }).click();
  await expect(page.locator("ol li").filter({ hasText: title })).toHaveCount(0);
});
